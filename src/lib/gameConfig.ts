const CONFIGS: Record<string, GameConfig> = Object.fromEntries(
  SEEDS.map((seed) => {
    const d = KIND_DEFAULTS[seed.kind];
    return [
      seed.id,
      {
        id: seed.id,
        kind: seed.kind,
        castEvent: seed.castEvent,
        voteEvent: seed.voteEvent,
        hasVote: seed.hasVote,
        icon: seed.icon,
        accent: seed.accent,
        title: seed.title,
        tagline: seed.tagline,
        header: seed.header,
        promptLead: seed.promptLead,
        startLabel: seed.startLabel ?? d.startLabel,
        progressVerb: seed.progressVerb ?? d.progressVerb,
        everyoneDone: seed.everyoneDone ?? d.everyoneDone,
        revealLabel: seed.revealLabel ?? d.revealLabel,
        nextLabel: seed.nextLabel ?? d.nextLabel,
        whoTitle: seed.whoTitle ?? d.whoTitle,
        doneLabel: seed.doneLabel ?? d.doneLabel,
        sideNote: seed.sideNote ?? d.sideNote,
        waitingSub: seed.waitingSub ?? d.waitingSub,
      } satisfies GameConfig,
    ];
  }),
);

export const GAME_CONFIGS = CONFIGS;

export function getGameConfig(id: string): GameConfig | undefined {
  return CONFIGS[id];
}

