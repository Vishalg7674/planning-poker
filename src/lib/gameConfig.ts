/**
 * Client-side config for the engine-backed games.
 *
 * The server owns the game rules and the prompt banks (server/games/registry.mjs
 * + server/games/data/*.json). This file is the *client* half of that registry:
 * it tells the shared GameRoom component which socket event to emit for a vote,
 * how to render the round, and what copy to show. Adding a game here + on the
 * server + in the catalog (src/lib/games.ts) ships it — no new page needed.
 */

import type { Accent } from './types';

export type GameKind = 'options' | 'teammate' | 'quiz' | 'estimate' | 'free' | 'health' | 'poll';

export interface GameConfig {
  id: string;
  kind: GameKind;
  /** Socket event the client emits to cast this game's vote (or submit an answer). */
  castEvent: string;
  /** `free` games only: the event the client emits during the vote phase. */
  voteEvent?: string;
  /** `free` games only: whether the room votes on the best answer after revealing. */
  hasVote?: boolean;
  icon: string;
  accent: Accent;
  title: string;
  /** One-line description shown on the create screen. */
  tagline: string;
  /** Header chip, e.g. "😂 Most Likely To". */
  header: string;
  /** Waiting-room start button. */
  startLabel: string;
  /** Lead-in above the prompt (or question). */
  promptLead: string;
  /** "X / Y picked", "X / Y chosen", "X / Y answered", "X / Y guessed". */
  progressVerb: string;
  /** "Everyone has picked", "Everyone has chosen", … */
  everyoneDone: string;
  /** Gold reveal button. */
  revealLabel: string;
  /** "Next Prompt", "Next Dilemma", "Next Question", "Next Round". */
  nextLabel: string;
  /** Results section title: "Who picked whom", "Who chose what", … */
  whoTitle: string;
  /** Sidebar status after voting: "Picked", "Chose", "Answered", "Guessed". */
  doneLabel: string;
  /** Sidebar note about privacy. */
  sideNote: string;
  /** Waiting-room sub copy for non-hosts. */
  waitingSub: string;
}

